function addTileService(androidManifest) {
  const app = AndroidConfig.Manifest.getMainApplicationOrThrow(androidManifest);
  const name = `.${TILE_SERVICE}`;
  app.service = (app.service || []).filter((s) => s.$['android:name'] !== name);
  app.service.push({
    $: {
      'android:name': name,
      'android:exported': 'true',
      'android:label': 'Talk to Pappu',
      'android:icon': `@drawable/${TILE_ICON}`,
      'android:permission': 'android.permission.BIND_QUICK_SETTINGS_TILE',
    },
    'intent-filter': [
      { action: [{ $: { 'android:name': 'android.service.quicksettings.action.QS_TILE' } }] },
    ],
  });
  return androidManifest;
}

function addAssistActivity(androidManifest) {
  const app = AndroidConfig.Manifest.getMainApplicationOrThrow(androidManifest);
  const name = `.${ASSIST_ACTIVITY}`;
  app.activity = (app.activity || []).filter((a) => a.$['android:name'] !== name);
  app.activity.push({
    $: {
      'android:name': name,
      'android:exported': 'true',
      'android:label': 'Talk to Pappu',
      'android:theme': '@android:style/Theme.Translucent.NoTitleBar',
      'android:excludeFromRecents': 'true',
      'android:noHistory': 'true',
      'android:taskAffinity': '',
    },
    'intent-filter': [
      {
        action: [{ $: { 'android:name': 'android.intent.action.ASSIST' } }],
        category: [{ $: { 'android:name': 'android.intent.category.DEFAULT' } }],
      },
    ],
  });
  return androidManifest;
}

function withEntryPointManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    addTileService(cfg.modResults);
    addAssistActivity(cfg.modResults);
    return cfg;
  });
}

function withEntryPointSources(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const pkg = cfg.android?.package;
      if (!pkg) throw new Error('withListenEntryPoints: expo.android.package is required');
      const main = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main');
      const javaDir = path.join(main, 'java', ...pkg.split('.'));
      const drawableDir = path.join(main, 'res', 'drawable');
      fs.mkdirSync(javaDir, { recursive: true });
      fs.mkdirSync(drawableDir, { recursive: true });
      fs.writeFileSync(path.join(javaDir, `${TILE_SERVICE}.kt`), tileServiceSource(pkg));
      fs.writeFileSync(path.join(javaDir, `${ASSIST_ACTIVITY}.kt`), assistActivitySource(pkg));
      fs.writeFileSync(path.join(drawableDir, `${TILE_ICON}.xml`), TILE_ICON_XML);
      return cfg;
    },
  ]);
}

function withListenEntryPoints(config) {
  return withEntryPointSources(withEntryPointManifest(config));
}

module.exports = withListenEntryPoints;
