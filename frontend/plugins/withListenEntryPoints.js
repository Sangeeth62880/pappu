/**
 * Android entry points that open pappu://listen ("press a button and talk").
 *
 * - Quick Settings tile "Talk to Pappu": a TileService that launches the deep link.
 * - Default digital assistant: an activity handling ACTION_ASSIST makes Pappu selectable
 *   in Settings > Default apps > Digital assistant app (the ASSISTANT role accepts an
 *   assist activity or a VoiceInteractionService). With no VoiceInteractionService,
 *   SystemUI starts this activity for the assist gesture / power button long press.
 *   It only forwards to the deep link.
 *
 * Both only open the app; listening itself happens in JS (listenTrigger.js).
 */
const fs = require('fs');
const path = require('path');
const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const LISTEN_URL = 'pappu://listen';
const TILE_SERVICE = 'ListenTileService';
const TILE_ICON = 'ic_listen_tile';
const ASSIST_ACTIVITY = 'AssistActivity';

function tileServiceSource(pkg) {
  return `package ${pkg}

import android.app.PendingIntent
import android.content.Intent
import android.net.Uri
import android.os.Build
import android.service.quicksettings.Tile
import android.service.quicksettings.TileService

/** Quick Settings tile "Talk to Pappu": opens ${LISTEN_URL}. Generated by withListenEntryPoints. */
class ${TILE_SERVICE} : TileService() {
  override fun onStartListening() {
    super.onStartListening()
    qsTile?.let {
      it.state = Tile.STATE_INACTIVE
      it.updateTile()
    }
  }

  override fun onClick() {
    super.onClick()
    // Recording needs the app in front, so a locked phone is asked to unlock first.
    if (isLocked) unlockAndRun { openListen() } else openListen()
  }

  private fun openListen() {
    val intent = Intent(Intent.ACTION_VIEW, Uri.parse("${LISTEN_URL}")).apply {
      setPackage(packageName)
      addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
    }
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.UPSIDE_DOWN_CAKE) {
      // API 34+: the Intent overload throws UnsupportedOperationException.
      val pending = PendingIntent.getActivity(
        this, 0, intent, PendingIntent.FLAG_IMMUTABLE or PendingIntent.FLAG_UPDATE_CURRENT
      )
      startActivityAndCollapse(pending)
    } else {
      @Suppress("DEPRECATION")
      startActivityAndCollapse(intent)
    }
  }
}
`;
}

function assistActivitySource(pkg) {
  return `package ${pkg}

import android.app.Activity
import android.content.Intent
import android.net.Uri
import android.os.Bundle

/** Assist gesture / power button (Pappu as digital assistant): opens ${LISTEN_URL}. Generated by withListenEntryPoints. */
class ${ASSIST_ACTIVITY} : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    startActivity(Intent(Intent.ACTION_VIEW, Uri.parse("${LISTEN_URL}")).apply {
      setPackage(packageName)
      addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
    })
    finish()
  }
}
`;
}

